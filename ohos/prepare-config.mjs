/** Generate platform overlays from the pinned upstream preset configurations. */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import yaml from 'js-yaml'

const root = resolve(import.meta.dirname, '..')
class Expression {
  constructor(source) { this.source = source }
}
const expression = new yaml.Type('tag:yaml.org,2002:js', {
  kind: 'scalar',
  instanceOf: Expression,
  construct: source => new Expression(source),
  represent: value => value.source,
})
const schema = yaml.DEFAULT_SCHEMA.extend([expression])
function entries(path) {
  const patches = yaml.load(readFileSync(resolve(root, path), 'utf8'), { schema })
  return patches.flatMap(patch => patch.insert ?? [])
}
function zshDescription(entry) {
  const description = entry.config.description
  if (!description.startsWith('Run commands in a bash shell')) throw new Error('Upstream persistent shell description changed')
  entry.config.description = description.replace('Run commands in a bash shell', 'Run commands in a zsh shell. Use zsh syntax. On HarmonyOS, exec ends the shell and resets its state; run commands directly to keep the session.')
}
function output(name, patches) {
  writeFileSync(resolve(root, 'ohos', name), '# Generated by prepare-config.mjs from the pinned upstream bundles.\n' + yaml.dump(patches, { schema, lineWidth: -1, noRefs: true }))
}

const preset = entries('packages/bundle/web-app/presets/minimal.patch.yml').find(entry => entry.id === 'preset-minimal')
if (!preset) throw new Error('Upstream minimal preset is missing')
const group = preset.config.plugins.find(entry => entry.id === 'persistent-shell')
const persistent = group?.config.find(entry => entry.id === 'persistent-bash')
if (!persistent) throw new Error('Upstream persistent shell group is missing')
zshDescription(persistent)
output('compat-web.patch.yml', [{ id: preset.id, name: preset.name, config: preset.config }])

const sdk = entries('packages/bundle/sdk-minimal/cordis.patch.yml').find(entry => entry.id === 'persistent-bash')
if (!sdk) throw new Error('Upstream standalone persistent shell is missing')
zshDescription(sdk)
output('compat-sdk-minimal.patch.yml', [
  { id: 'sandbox-policy', config: { mode: new Expression("process.env.DSH_PERMISSION_MODE ?? 'danger-full-access'"), workspaceRoot: new Expression('process.cwd()') } },
  { id: sdk.id, name: sdk.name, config: sdk.config },
])
console.log('Generated Web and standalone SDK HarmonyOS configuration overlays')
